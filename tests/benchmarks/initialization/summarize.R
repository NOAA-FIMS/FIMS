args<-commandArgs(TRUE)
input<-args[1]
output<-args[2]
dir.create(output,recursive=TRUE,showWarnings=FALSE)
runs<-jsonlite::fromJSON(file.path(input,"runs.json"))
stopifnot(nrow(runs)==8L,all(runs$exit_code==0))
phases<-list()
checks<-list()
for (year in unique(runs$years)) {
  reference<-readRDS(file.path(input,paste0(year,"-1-before"),paste0(year,"-numerics.rds")))
  for (i in which(runs$years==year)) {
    label<-runs$label[i]
    values<-readRDS(file.path(input,label,paste0(year,"-numerics.rds")))
    passed<-isTRUE(all.equal(values,reference,tolerance=1e-10))
    stopifnot(passed)
    checks[[label]]<-data.frame(label,passed)
    p<-read.csv(file.path(input,label,paste0(year,"-summary.csv")))
    p$variant<-runs$variant[i]
    p$run<-label
    phases[[label]]<-p
  }
}
phases<-do.call(rbind,phases)
summary<-aggregate(elapsed~years+phase+variant,phases,median)
write.csv(runs,file.path(output,"runs.csv"),row.names=FALSE)
write.csv(phases,file.path(output,"phases.csv"),row.names=FALSE)
write.csv(summary,file.path(output,"summary.csv"),row.names=FALSE)
write.csv(do.call(rbind,checks),file.path(output,"validation.csv"),row.names=FALSE)
print(summary)
